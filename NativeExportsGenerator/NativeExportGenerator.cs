			    /// <returns><see cref="NssStatus.NSS_STATUS_SUCCESS"/> if a shadow entry was found, or <see cref="NssStatus.NSS_STATUS_NOTFOUND"/> if enumeration is complete.</returns>
			    [UnmanagedCallersOnly(EntryPoint = "_nss_{{module}}_getspent_r")]
			    public static NssStatus nss_getspent_r(IntPtr resultStructPtr, IntPtr bufferPtr, nuint bufferLengthValue, IntPtr errorNumberPtr) {
					// Instantiate the NSS provider, and call the equivalent method.
					//using {{nssProvider}} provider = new {{nssProvider}}();
