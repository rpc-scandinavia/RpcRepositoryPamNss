			using System;
			using System.Runtime.InteropServices;
			namespace RpcScandinavia.Repository.PamNss;
			
			/// <summary>
			/// Provides the low-level GNU C Library (glibc) Name Service Switch (NSS) entry points.
			///
			/// Why non-reentrant functions are omitted:
			/// Functions like getpwnam() (without the _r) are legacy, thread-unsafe functions provided directly by glibc to user
			/// applications. When a legacy application calls getpwnam(), glibc itself handles allocating a thread-local static
			/// buffer and invokes the reentrant _getpwnam_r function to populate it.
			/// NSS service modules are strictly required to implement only the reentrant interface. Exporting non-reentrant
			/// function symbols would have no effect because glibc's NSS loader never searches for them.
			/// </summary>
			public static class NssExports {
			
				/// <summary>
				/// Instantiate the NSS provider, or fall back to the base provider if that fail.
				/// </summary>
				/// <returns></returns>
				private static NssProviderBase CreateProvider() {
					try {
						return new {{nssProvider}}();			
					} catch {
						return new NssProviderBase(); 				
					}
				} // CreateProvider
			
				#region Password
			    //------------------------------------------------------------------------------------------------------------------
			    // Password.
			    //------------------------------------------------------------------------------------------------------------------
			    /// <summary>
			    /// Rewinds or opens the stream to the beginning of the password database.
			    ///
			    /// See <see href="https://manpages.debian.org/testing/manpages-dev/setpwent.3.en.html"/>.
			    /// </summary>
			    /// <param name="stayopen">Whether to keep the connection/file descriptor open across lookups.</param>
			    /// <returns>Always returns <see cref="NssStatus.NSS_STATUS_SUCCESS"/>.</returns>
			    [UnmanagedCallersOnly(EntryPoint = "_nss_{{module}}_setpwent")]
			    public static NssStatus nss_setpwent(Int32 stayopen) {
					// Instantiate the NSS provider, and call the equivalent method.
					//using {{nssProvider}} provider = new {{nssProvider}}();
					using NssProviderBase provider = NssExports.CreateProvider();
					return provider.nss_setpwent(stayopen);
			    } // nss_setpwent
			
			    /// <summary>
			    /// Closes the password database stream and releases associated enumeration resources.
			    ///
			    /// See <see href="https://manpages.debian.org/testing/manpages-dev/endpwent.3.en.html"/>.
			    /// </summary>
			    /// <returns>Always returns <see cref="NssStatus.NSS_STATUS_SUCCESS"/>.</returns>
			    [UnmanagedCallersOnly(EntryPoint = "_nss_{{module}}_endpwent")]
			    public static NssStatus nss_endpwent() {
					// Instantiate the NSS provider, and call the equivalent method.
					//using {{nssProvider}} provider = new {{nssProvider}}();
