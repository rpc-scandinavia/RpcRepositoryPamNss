using System;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
namespace RpcScandinavia.Repository.PamNss.SourceGenerator;

/// <summary>
/// Source generator that generates the native exported methods.
/// This is done as an alternative to a global using alias, when specifying the PAM/NSS provider class, and to use the
/// correct NSS service name in the export EntryPoint.
/// </summary>
[Generator]
public sealed class NativeExportGenerator : IIncrementalGenerator {

	#region Initialise
	//------------------------------------------------------------------------------------------------------------------
	// Initialise.
	//------------------------------------------------------------------------------------------------------------------
	public void Initialize(IncrementalGeneratorInitializationContext context) {
		// Get property values from the project file.
		IncrementalValueProvider<String> pamClass = context.AnalyzerConfigOptionsProvider
			.Select((provider, _) => provider.GlobalOptions.TryGetValue("build_property.PamProviderClass", out String providerClassName)
				? providerClassName
				: "RpcRepositoryPamProvider"
			);

		IncrementalValueProvider<String> nssClass = context.AnalyzerConfigOptionsProvider
			.Select((provider, _) => provider.GlobalOptions.TryGetValue("build_property.NssProviderClass", out String providerClassName)
				? providerClassName
				: "RpcRepositoryNssProvider"
			);

		IncrementalValueProvider<String> moduleName = context.AnalyzerConfigOptionsProvider
			.Select((provider, _) => provider.GlobalOptions.TryGetValue("build_property.NssServiceName", out String moduleName)
				? moduleName
				: "RpcRepositoryPamNss"
			);

		IncrementalValueProvider<String> projectDir = context.AnalyzerConfigOptionsProvider
			.Select((provider, _) => provider.GlobalOptions.TryGetValue("build_property.MSBuildProjectDirectory", out String path)
				? path .Trim()
				: String.Empty
			);

		// Register PAM output.
		IncrementalValueProvider<(String Left, String Right)> combinedPam = projectDir.Combine(pamClass);
		context.RegisterSourceOutput(combinedPam, static (spc, data) => {
			(String path, String pam) = data;
			spc.AddSource("NativePamExports.g.cs", SourceText.From(GeneratePam(path, pam), Encoding.UTF8));
		});

		// Register NSS output.
		IncrementalValueProvider<((String Left, String Right) Left, String Right)> combinedNss =
			projectDir.Combine(nssClass).Combine(moduleName);
		context.RegisterSourceOutput(combinedNss, static (spc, data) => {
			((String path, String nss), String module) = data;
			spc.AddSource("NativeNssExports.g.cs", SourceText.From(GenerateNss(path, nss, module), Encoding.UTF8));
		});
	} // Initialize
	#endregion

