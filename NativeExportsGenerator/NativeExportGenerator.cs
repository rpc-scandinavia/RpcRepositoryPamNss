					return provider.nss_endpwent();
			    } // nss_endpwent
			
			    /// <summary>
			    /// Reads the next entry from the password database into the caller-provided buffer.
			    ///
			    /// See <see href="https://manpages.debian.org/testing/manpages-dev/getpwent_r.3.en.html"/>.
			    /// </summary>
			    /// <param name="resultStructPtr">Pointer to the <c>passwd</c> structure to populate upon a successful match.</param>
			    /// <param name="bufferPtr">Pointer to the working memory buffer allocated by glibc.</param>
			    /// <param name="bufferLengthValue">The size in bytes of the working buffer.</param>
			    /// <param name="errorNumberPtr">Pointer to an error integer to set if the buffer is too small (ERANGE) or on failure.</param>
			    /// <returns><see cref="NssStatus.NSS_STATUS_SUCCESS"/> if an entry was found, or <see cref="NssStatus.NSS_STATUS_NOTFOUND"/> if enumeration is complete.</returns>
			    [UnmanagedCallersOnly(EntryPoint = "_nss_{{module}}_getpwent_r")]
			    public static NssStatus nss_getpwent_r(IntPtr resultStructPtr, IntPtr bufferPtr, nuint bufferLengthValue, IntPtr errorNumberPtr) {
					// Instantiate the NSS provider, and call the equivalent method.
					//using {{nssProvider}} provider = new {{nssProvider}}();
					using NssProviderBase provider = NssExports.CreateProvider();
					return provider.nss_getpwent_r(resultStructPtr, bufferPtr, bufferLengthValue, errorNumberPtr);
			    } // nss_getpwent_r
			
			    /// <summary>
			    /// Looks up a password database entry by username.
			    ///
			    /// See <see href="https://manpages.debian.org/testing/manpages-dev/getpwnam_r.3.en.html"/>.
			    /// </summary>
			    /// <param name="userNameStringPtr">Pointer to a null-terminated string representing the target user name.</param>
			    /// <param name="resultStructPtr">Pointer to the <c>passwd</c> structure to populate upon a successful match.</param>
			    /// <param name="bufferPtr">Pointer to the working memory buffer allocated by glibc.</param>
			    /// <param name="bufferLengthValue">The size in bytes of the working buffer.</param>
			    /// <param name="errorNumberPtr">Pointer to an error integer to set if the buffer is too small (ERANGE) or if the user is missing (ENOENT).</param>
			    /// <returns><see cref="NssStatus.NSS_STATUS_SUCCESS"/> if the user was found, otherwise <see cref="NssStatus.NSS_STATUS_NOTFOUND"/>.</returns>
			    [UnmanagedCallersOnly(EntryPoint = "_nss_{{module}}_getpwnam_r")]
			    public static NssStatus nss_getpwnam_r(IntPtr userNameStringPtr, IntPtr resultStructPtr, IntPtr bufferPtr, nuint bufferLengthValue, IntPtr errorNumberPtr) {
