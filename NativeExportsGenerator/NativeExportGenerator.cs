			    /// Rewinds or opens the stream to the beginning of the shadow password database.
			    ///
			    /// See <see href="https://manpages.debian.org/testing/manpages-dev/setspent.3.en.html"/>.
			    /// </summary>
			    /// <param name="stayopen">Whether to keep the connection open across lookups.</param>
